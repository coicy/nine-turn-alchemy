// Rebuild editable rig.json and offline-capable source.js. No image pixels are modified.
const fs=require('fs'),path=require('path');
const out=__dirname,W=1024,H=1536;
const bones=[
 ['root',-1,512,1180],['spine',0,512,880],['chest',1,512,520],
 ['neck',2,530,415],['head',3,530,355],
 ['leftUpper',2,310,470],['leftFore',5,220,780],['leftHand',6,400,890],
 ['rightUpper',2,725,470],['rightFore',8,830,850],['rightHand',9,830,1110]
].map(([name,parent,x,y])=>({name,parent,bind:[x,y]}));
const clamp=x=>Math.max(0,Math.min(1,x)),smooth=x=>{x=clamp(x);return x*x*(3-2*x);};
function weights(x,y){
 let v=Array(bones.length).fill(0);
 // Shared continuous surface: head/neck/chest transitions have no cut edges.
 let head=1-smooth((y-335)/95),neck=(1-head)*(1-smooth((y-415)/95));
 let spine=smooth((y-650)/280),root=smooth((y-1130)/300);
 v[4]=head;v[3]=neck;let body=1-head-neck;
 v[2]=body*(1-spine);v[1]=body*spine*(1-root);v[0]=body*spine*root;
 const left=(1-smooth((x-300)/140))*smooth((y-420)/110)*(1-smooth((y-1050)/140));
 const rightEdge=670+95*smooth((y-900)/180);
 const right=smooth((x-rightEdge)/(120-45*smooth((y-900)/180)))*smooth((y-430)/110)*(1-smooth((y-1300)/100));
 let arm=Math.max(left,right);v=v.map(a=>a*(1-arm));
 if(left>right){let fore=smooth((y-650)/190),hand=smooth((x-330)/100)*smooth((y-815)/65);v[5]+=arm*(1-fore);v[6]+=arm*fore*(1-hand);v[7]+=arm*fore*hand;}
 else{let fore=smooth((y-750)/190),hand=smooth((y-1030)/110);v[8]+=arm*(1-fore);v[9]+=arm*fore*(1-hand);v[10]+=arm*fore*hand;}
 let a=v.map((w,i)=>[i,w]).filter(a=>a[1]>1e-8).sort((a,b)=>b[1]-a[1]).slice(0,4),s=a.reduce((r,a)=>r+a[1],0);return a.map(([i,w])=>[i,w/s]);
}
let vertices=[],triangles=[],cols=32,rows=48;
for(let j=0;j<=rows;j++)for(let i=0;i<=cols;i++){let x=i*W/cols,y=j*H/rows;vertices.push({xy:[x,y],weights:weights(x,y)});}
for(let j=0;j<rows;j++)for(let i=0;i<cols;i++){let a=j*(cols+1)+i,b=a+1,c=a+cols+1,d=c+1;triangles.push([a,b,d],[a,d,c]);}
const rig={version:1,name:'行商 V55',texture:'master.png',size:[W,H],bones,vertices,triangles,
 clips:{idle:{duration:8,description:'轻微呼吸，双臂保持原有遮挡',channels:[]},greet:{duration:8,description:'胸肩前倾、颈部跟随、头部小幅点头，收回等候',channels:[
  [1,'rotation',-.012,.5,2.8],[2,'rotation',.018,.5,2.8],[3,'rotation',.012,.5,2.8],[4,'rotation',-.024,.5,2.8],
  [5,'rotation',.007,.5,2.8],[6,'rotation',-.012,.5,2.8],[8,'rotation',-.004,.5,2.8],
  [3,'rotation',.008,3.4,1.8],[4,'rotation',.014,3.4,1.8],[3,'y',6,3.4,1.8],[4,'y',4,3.4,1.8]
 ]},test:{duration:8,description:'依次测试头颈、左臂、右臂，小幅范围；不用于游戏表演',channels:[
  [4,'rotation',.04,0,2],[3,'rotation',-.015,0,2],[5,'rotation',.018,2,2],[6,'rotation',-.025,2,2],
  [8,'rotation',-.018,4,2],[9,'rotation',.02,4,2],[1,'rotation',.006,6,2],[2,'rotation',-.008,6,2]
 ]}},
 limits:{spine:.02,chest:.025,neck:.025,head:.04,leftUpper:.018,leftFore:.025,leftHand:.012,rightUpper:.018,rightFore:.02,rightHand:.012},
 regions:[{name:'头颈',bones:[3,4]},{name:'躯干',bones:[0,1,2]},{name:'左袖臂',bones:[5,6,7]},{name:'右袖臂',bones:[8,9,10]}]};
fs.writeFileSync(path.join(out,'rig.json'),JSON.stringify(rig));
fs.writeFileSync(path.join(out,'source.js'),'// Generated by build-rig.cjs; edit rig source and rebuild. Original raster is unchanged.\nwindow.MerchantRigSource='+JSON.stringify(rig)+';\nwindow.MerchantTexture="data:image/png;base64,'+fs.readFileSync(path.join(out,'master.png')).toString('base64')+'";\n');
