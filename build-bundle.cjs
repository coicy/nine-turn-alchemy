#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = __dirname;
const checkOnly = process.argv.includes('--check');
const manifestPath = path.join(root, 'bundle-manifest.json');
const versionPath = path.join(root, 'VERSION');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const version = fs.readFileSync(versionPath, 'utf8').trim();
const headerComment = `/* Nine Turn Alchemy bundle (${version}) - generated by build-bundle.cjs; edit source files, not this file. */\n`;

function buildCss() {
  const parts = [headerComment];
  for (const file of manifest.styles) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) throw new Error(`Missing stylesheet in manifest: ${file}`);
    const body = fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, '');
    parts.push(`/* === ${file} === */\n${body.trimEnd()}\n`);
  }
  return parts.join('\n');
}

function buildJs() {
  const parts = [headerComment];
  for (const file of manifest.scripts) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) throw new Error(`Missing script in manifest: ${file}`);
    const body = fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, '');
    parts.push(`/* === ${file} === */\n${body.trimEnd()}`);
  }
  const bundle = parts.join('\n;\n') + '\n';
  // Validate the combined JS bundle parses as one script cleanly.
  new Function(bundle);
  return bundle;
}

const cssBundle = buildCss();
const jsBundle = buildJs();
const cssOut = path.join(root, 'bundle.css');
const jsOut = path.join(root, 'bundle.js');

if (checkOnly) {
  const sameCss = fs.existsSync(cssOut) && fs.readFileSync(cssOut, 'utf8') === cssBundle;
  const sameJs = fs.existsSync(jsOut) && fs.readFileSync(jsOut, 'utf8') === jsBundle;
  if (!sameCss || !sameJs) {
    console.error(`Bundle out of date (css=${sameCss}, js=${sameJs}). Run: node build-bundle.cjs`);
    process.exit(1);
  }
  console.log(`PASS bundle check (${version}): ${manifest.styles.length} CSS (${(cssBundle.length / 1024).toFixed(1)} KB), ${manifest.scripts.length} JS (${(jsBundle.length / 1024).toFixed(1)} KB)`);
} else {
  fs.writeFileSync(cssOut, cssBundle, 'utf8');
  fs.writeFileSync(jsOut, jsBundle, 'utf8');
  console.log(`BUILT bundle (${version}): bundle.css ${(cssBundle.length / 1024).toFixed(1)} KB (${manifest.styles.length} files), bundle.js ${(jsBundle.length / 1024).toFixed(1)} KB (${manifest.scripts.length} files)`);
}
